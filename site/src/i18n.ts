const dicts: Record<Lang, Dict> = { pt, en };

let current: Lang = "pt";
const listeners: Array<() => void> = [];

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("adc-lang");
    if (saved === "pt" || saved === "en") return saved;
  } catch {
    /* armazenamento indisponível */
  }
  return (navigator.language || "pt").toLowerCase().startsWith("pt") ? "pt" : "en";
}

export function getLang(): Lang {
  return current;
}

export function locale(): string {
  return current === "pt" ? "pt-BR" : "en-US";
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  // singular quando n é 1 e existe a forma "<chave>.one"
  const one = String(vars.n) === "1" ? dicts[current][`${key}.one`] : undefined;
  const s = one ?? dicts[current][key] ?? dicts.pt[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function onLangChange(fn: () => void) {
  listeners.push(fn);
}

export function setLang(lang: Lang) {
  current = lang;
  try {
    localStorage.setItem("adc-lang", lang);
  } catch {
    /* sem armazenamento: o idioma vale só nesta visita */
  }
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  applyStatic();
  listeners.forEach((fn) => fn());
}

/** Textos estáticos do HTML (data-i18n). Os valores vêm deste arquivo, nunca de dados externos. */
export function applyStatic(vars: Record<string, string | number> = {}) {
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const v = t(el.dataset.i18n!, vars);
    if (v.includes("<")) el.innerHTML = v;
    else el.textContent = v;
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-attr]").forEach((el) => {
    el.dataset.i18nAttr!.split(";").forEach((pair) => {
      const [attr, key] = pair.split(":");
      el.setAttribute(attr, t(key));
    });
  });
  document.title = current === "pt" ? "Além da Curva | Massa e raio de exoplanetas" : "Beyond the Curve | Exoplanet mass and radius";
}
